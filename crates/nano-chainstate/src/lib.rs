fn phantom_unlock_transaction(
    network: Network,
    stacks_block_height: u64,
    events: Vec<StacksTransactionEvent>,
) -> Option<ObservedTransaction> {
    if events.is_empty() {
        return None;
    }
    let mut memo = [0_u8; 34];
    let message = format!("Block {stacks_block_height} token unlocks");
    let length = message.len().min(memo.len());
    memo[..length].copy_from_slice(&message.as_bytes()[..length]);
    let transaction = Transaction::new(
        TransactionVersion::for_network(network),
        TransactionAuth::Standard(SpendingCondition::Singlesig(SinglesigCondition {
            hash_mode: SinglesigHashMode::P2pkh,
            signer: nano_primitives::Hash160::from_bytes([0; 20]),
            nonce: 0,
            fee: 0,
            key_encoding: KeyEncoding::Uncompressed,
            signature: MessageSignature::from_bytes([0; 65]),
        })),
        TransactionPayloadData::TokenTransfer {
            recipient: Principal::Standard(
                network
                    .boot_address()
                    .parse()
                    .expect("the boot address is a valid Stacks address"),
            ),
            amount: 0,
            memo,
        },
    );
    let receipt = TransactionReceipt {
        txid: transaction.txid(),
        status: TransactionStatus::Success,
        committed: true,
        result: TransactionResult {
            value: Some(Value::okay_true()),
            cost: ExecutionCost::ZERO,
            assets: AssetMap::new(),
            events,
        },
    };
    Some(ObservedTransaction {
        transaction,
        receipt,
    })
}

