/// How a block's committed state root is established during execution.
#[derive(Clone, Copy)]
enum RootPolicy<'a> {
    /// Derive the root, write it into the header, and sign as the miner.
    Mine(&'a StacksPrivateKey),
    /// Reject the block before sealing when the derived root disagrees.
    Verify,
    /// Accept whatever root execution produces.
    Trust,
}

/// What executing one block produced: its sealed state, what it cost, and the
/// receipt of every transaction it carried.
#[derive(Clone, Debug, PartialEq)]
pub struct AppliedBlock {
    pub bitcoin_height: u64,
    pub execution: ExecutionResult,
    pub execution_cost: ExecutionCost,
    pub receipts: Vec<TransactionReceipt>,
    /// Observer-only transactions generated by protocol state transitions.
    /// They are not block transactions and never participate in the state root.
    pub observer_transactions: Vec<ObservedTransaction>,
    /// The miner rewards this block matured, which only a tenure-start block
    /// does. Reported here because execution is the only place that knows them:
    /// they are credited from the tenure accounting and leave no trace in the
    /// block.
    pub matured_rewards: Vec<NativeStxCredit>,
    /// New STX in the first matured credit. Any remainder in that credit is
    /// anchored transaction fees, which an observer reports separately.
    pub matured_coinbase: u128,
    pub matured_anchored_fees: u128,
    /// The reward set this block computed, if it is the prepare-phase block that
    /// computed one. Not "the set of this cycle" — a node can read that any
    /// time; this is the transition, which is what an observer is told about.
    pub reward_set: Option<signers::DerivedRewardSet>,
}

/// A transaction stacks-core synthesizes only for event observers.
#[derive(Clone, Debug, PartialEq)]
pub struct ObservedTransaction {
    pub transaction: Transaction,
    pub receipt: TransactionReceipt,
}

/// Native accounting that is applied when an epoch-4 block is finalized.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct NativeBlockEffects {
    pub credits: Vec<NativeStxCredit>,
    pub liquid_supply_increase: u128,
}

/// One liquid-STX credit produced by native chainstate accounting.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct NativeStxCredit {
    pub recipient: PrincipalData,
    pub amount: u128,
}

fn matured_reward_amounts(effects: &NativeBlockEffects) -> Result<(u128, u128), ChainStateError> {
    let coinbase = effects.liquid_supply_increase;
    let anchored_fees = effects
        .credits
        .first()
        .map_or(0, |credit| credit.amount)
        .checked_sub(coinbase)
        .ok_or_else(|| {
            ChainStateError::InvalidTransaction(
                "matured liquid supply exceeds the first reward credit".to_owned(),
            )
        })?;
    Ok((coinbase, anchored_fees))
}

/// Number of sortition-created tenures before a miner reward matures.
pub const MINER_REWARD_MATURITY: u64 = 100;

/// How many tenures' earnings are kept.
///
/// The deepest read is `matured - 1`, 101 below the tip, so this is that plus a
/// full maturity window of margin — and it is the same 201 a checkpoint has to
/// carry, which is not a coincidence: both numbers are "what a node can still be
/// asked to pay".
const EARNINGS_KEPT: u64 = 2 * MINER_REWARD_MATURITY + 1;

/// What a tenure earned for the recipient it pays once it matures.
///
/// Both halves go to the same recipient — this tenure's — but not in the same
/// block. The coinbase matures `MINER_REWARD_MATURITY` tenures later; the fees
/// this tenure's own transactions paid mature one tenure after that, because
/// stacks-core cannot total them until the *next* tenure change proves the
/// tenure is over, and so records them in the next tenure's payment schedule
/// (`MinerPaymentTxFees::Nakamoto { parent_fees }`).
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct TenureEarnings {
    pub recipient: PrincipalData,
    pub coinbase: u128,
    /// The fees the transactions of *this* tenure paid, not those of any other.
    pub fees: u128,
}

impl TenureEarnings {
    /// Read a tenure's reward recipient from the coinbase transaction that
    /// starts it: the recipient the coinbase names, or else the miner that
    /// signed it (`nakamoto/tenure.rs`, `make_scheduled_miner_reward`).
    #[must_use]
    pub fn from_tenure_start(block: &NakamotoBlock, coinbase: u128) -> Option<Self> {
        let transaction = tenure_coinbase(block)?;
        let named = match transaction.payload().data() {
            TransactionPayloadData::NakamotoCoinbase { recipient, .. } => recipient.clone(),
            TransactionPayloadData::CoinbaseToAltRecipient { recipient, .. } => {
                Some(recipient.clone())
            }
            _ => None,
        };
        let recipient = match named {
            Some(recipient) => principal_from_codec(&recipient).ok()?,
            None => principal_from_address(transaction.origin_address()?).ok()?,
        };
        Some(Self {
            recipient,
            coinbase,
            fees: 0,
        })
    }
}

/// The coinbase transaction a tenure-start block carries, in any of its forms.
fn tenure_coinbase(block: &NakamotoBlock) -> Option<&Transaction> {
    block.transactions.iter().find(|transaction| {
        matches!(
            transaction.payload().data(),
            TransactionPayloadData::NakamotoCoinbase { .. }
                | TransactionPayloadData::CoinbaseToAltRecipient { .. }
                | TransactionPayloadData::Coinbase { .. }
        )
    })
}

/// The miner that signed a tenure's coinbase, which is not always who it pays.
///
/// `miner_address` in a matured miner reward, and the one field of one that a
/// credit cannot be read backwards into: stacks-core takes it from the coinbase's
/// origin while the *recipient* is whoever the coinbase named, falling back to the
/// same origin when it named nobody (`make_scheduled_miner_reward`). A coinbase
/// paying an alternate recipient is where the two part company.
#[must_use]
pub fn tenure_miner_address(block: &NakamotoBlock) -> Option<nano_address::StacksAddress> {
    tenure_coinbase(block)?.origin_address()
}

/// The coinbase a sortition emits, which the burnchain schedule fixes.
///
/// From epoch 3.1 the emission follows SIP-029's interval table, and every
/// sortition also collects the per-block bonus the pre-mine funded plus the
/// emissions of the burn blocks since the last sortition
/// (`burn/sortition.rs`, `accumulated_coinbase_ustx`).
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct CoinbaseSchedule {
    pub mainnet: bool,
    pub first_bitcoin_height: u64,
    pub initial_mining_bonus: u128,
}

/// SIP-029 emissions in uSTX by effective height — the height above the chain's
/// own first burn block — for testnet then mainnet.
///
/// Mirrors `COINBASE_INTERVALS_TESTNET` and `COINBASE_INTERVALS_MAINNET`
/// (`stacks-common/src/types/mod.rs`), including the last interval, which is
/// SIP-045 restoring 1,000 STX at the epoch 4.0 boundary. Written as effective
/// heights because that is the unit `coinbase_reward_sip029` compares against;
/// giving them as absolute Bitcoin heights answers 1,000 STX for the whole
/// 500-STX era, which only shows up when a tenure from before the boundary
/// matures after it.
const TESTNET_EMISSIONS: [(u64, u128); 6] = [
    (0, 1_000_000_000),
    (77_777, 500_000_000),
    (77_777 * 7, 250_000_000),
    (77_777 * 14, 125_000_000),
    (77_777 * 21, 62_500_000),
    (
        TESTNET_STACKS_40_BURN_HEIGHT - TESTNET_GENESIS_BURN_HEIGHT,
        1_000_000_000,
    ),
];
const MAINNET_EMISSIONS: [(u64, u128); 3] = [
    (0, 1_000_000_000),
    (278_950, 500_000_000),
    (
        MAINNET_STACKS_40_BURN_HEIGHT - MAINNET_GENESIS_BURN_HEIGHT,
        1_000_000_000,
    ),
];

const MAINNET_GENESIS_BURN_HEIGHT: u64 = 666_050;
const MAINNET_STACKS_40_BURN_HEIGHT: u64 = 960_230;
const TESTNET_GENESIS_BURN_HEIGHT: u64 = 2_000_000;
const TESTNET_STACKS_40_BURN_HEIGHT: u64 = 40_000_000;

impl CoinbaseSchedule {
    /// The emission of one sortition at a Bitcoin height.
    #[must_use]
    pub fn emission_at(&self, bitcoin_height: u64) -> u128 {
        let effective = bitcoin_height.saturating_sub(self.first_bitcoin_height);
        let intervals: &[(u64, u128)] = if self.mainnet {
            &MAINNET_EMISSIONS
        } else {
            &TESTNET_EMISSIONS
        };
        intervals
            .iter()
            .rev()
            .find(|(start, _)| effective >= *start)
            .map_or(0, |(_, emission)| *emission)
    }

    /// What a sortition collects on top of its own emission: the bonus for
    /// every burn block since the last sortition, and those blocks' emissions.
    ///
    /// `previous_sortition` is the last Bitcoin height that chose a miner, and
    /// is absent only for the first sortition a chain ever holds.
    #[must_use]
    pub fn accumulated_at(&self, bitcoin_height: u64, previous_sortition: Option<u64>) -> u128 {
        let Some(previous) = previous_sortition else {
            return 0;
        };
        let mut accumulated = 0_u128;
        let mut height = bitcoin_height;
        while height > previous {
            accumulated = accumulated.saturating_add(self.initial_mining_bonus);
            height -= 1;
            if height > previous {
                accumulated = accumulated.saturating_add(self.emission_at(height));
            }
        }
        accumulated
    }
}

/// SIP-031 emissions in uSTX, by the Bitcoin height each interval starts at.
///
/// Testnet runs the schedule from 71,525 at one interval every 360 burn blocks
/// (`stacks-common/src/types/mod.rs`, `SIP031_EMISSION_INTERVALS_*`).
const TESTNET_SIP_031_EMISSIONS: [(u64, u128); 6] = [
    (71_525 + 360, 1_000),
    (71_525 + 360 * 2, 2_000),
    (71_525 + 360 * 3, 3_000),
    (71_525 + 360 * 4, 4_000),
    (71_525 + 360 * 5, 5_000),
    (71_525 + 360 * 6, 0),
];
const MAINNET_SIP_031_EMISSIONS: [(u64, u128); 6] = [
    (907_740, 475_000_000),
    (960_300, 1_140_000_000),
    (1_012_860, 1_705_000_000),
    (1_065_420, 1_305_000_000),
    (1_117_980, 1_155_000_000),
    (1_170_540, 0),
];

/// The SIP-031 emission a tenure starting at this Bitcoin height mints.
///
/// Unlike the coinbase, the schedule is keyed on the absolute Bitcoin height
/// rather than an offset from the chain's first burn block.
#[must_use]
pub fn sip_031_emission(network: Network, bitcoin_height: u64) -> u128 {
    let intervals: &[(u64, u128)] = if network.is_mainnet() {
        &MAINNET_SIP_031_EMISSIONS
    } else {
        &TESTNET_SIP_031_EMISSIONS
    };
    intervals
        .iter()
        .rev()
        .find(|(start, _)| bitcoin_height >= *start)
        .map_or(0, |(_, amount)| *amount)
}

/// Checkpointed native accounting required to finalize future tenure-start blocks.
///
/// A checkpoint carries the effects that mature over the tenures right after it,
/// because those were earned before nano had any history. Everything later is
/// derived from the tenures nano executed itself.
#[derive(Clone, Debug, Default, Eq, PartialEq)]
pub struct TenureAccounting {
    matured_effects: BTreeMap<u64, NativeBlockEffects>,
    earnings: BTreeMap<u64, TenureEarnings>,
    schedule: Option<CoinbaseSchedule>,
    /// The tenure whose own start block was executed here, and so the only one
    /// whose fees can be counted from the blocks that follow.
    started: Option<u64>,
}

impl TenureAccounting {
    /// Decode portable checkpoint accounting from JSON.
    pub fn from_json(bytes: &[u8]) -> Result<Self, TenureAccountingError> {
        Self::from_checkpoint(
            serde_json::from_slice(bytes)
                .map_err(|error| TenureAccountingError::InvalidCheckpoint(error.to_string()))?,
        )
    }

    fn from_checkpoint(
        checkpoint: TenureAccountingCheckpoint,
    ) -> Result<Self, TenureAccountingError> {
        let mut accounting = Self {
            schedule: checkpoint
                .coinbase_schedule
                .map(|schedule| CoinbaseSchedule {
                    mainnet: schedule.mainnet,
                    first_bitcoin_height: schedule.first_bitcoin_height,
                    initial_mining_bonus: schedule.initial_mining_bonus_ustx,
                }),
            ..Self::default()
        };
        for tenure in checkpoint.tenures {
            accounting.seed_earnings(
                tenure.coinbase_height,
                TenureEarnings {
                    recipient: PrincipalData::parse(&tenure.recipient).map_err(|error| {
                        TenureAccountingError::InvalidCheckpoint(error.to_string())
                    })?,
                    coinbase: tenure.coinbase,
                    fees: tenure.fees,
                },
            );
        }
        for entry in checkpoint.matured_effects {
            let credits = entry
                .credits
                .into_iter()
                .map(|credit| {
                    Ok(NativeStxCredit {
                        recipient: PrincipalData::parse(&credit.recipient).map_err(|error| {
                            TenureAccountingError::InvalidCheckpoint(error.to_string())
                        })?,
                        amount: credit.amount,
                    })
                })
                .collect::<Result<Vec<_>, TenureAccountingError>>()?;
            accounting.record_matured_effects(
                entry.coinbase_height,
                NativeBlockEffects {
                    credits,
                    liquid_supply_increase: entry.liquid_supply_increase,
                },
            )?;
        }
        accounting.started = checkpoint.started;
        Ok(accounting)
    }

    /// Encode this accounting in the same JSON a checkpoint carries.
    ///
    /// A node commits it with every block it seals, so that a restart resumes
    /// owing exactly what it owed rather than what its checkpoint owed.
    pub fn to_json(&self) -> Result<Vec<u8>, TenureAccountingError> {
        serde_json::to_vec(&self.to_checkpoint())
            .map_err(|error| TenureAccountingError::InvalidCheckpoint(error.to_string()))
    }

    fn to_checkpoint(&self) -> TenureAccountingCheckpoint {
        TenureAccountingCheckpoint {
            matured_effects: self
                .matured_effects
                .iter()
                .map(|(height, effects)| TenureAccountingCheckpointEntry {
                    coinbase_height: *height,
                    credits: effects
                        .credits
                        .iter()
                        .map(|credit| TenureAccountingCheckpointCredit {
                            recipient: credit.recipient.to_string(),
                            amount: credit.amount,
                        })
                        .collect(),
                    liquid_supply_increase: effects.liquid_supply_increase,
                })
                .collect(),
            tenures: self
                .earnings
                .iter()
                .map(|(height, earnings)| TenureAccountingCheckpointTenure {
                    coinbase_height: *height,
                    recipient: earnings.recipient.to_string(),
                    coinbase: earnings.coinbase,
                    fees: earnings.fees,
                })
                .collect(),
            coinbase_schedule: self
                .schedule
                .map(|schedule| TenureAccountingCheckpointSchedule {
                    mainnet: schedule.mainnet,
                    first_bitcoin_height: schedule.first_bitcoin_height,
                    initial_mining_bonus_ustx: schedule.initial_mining_bonus,
                }),
            started: self.started,
        }
    }

    /// Record the effects that mature when the given coinbase height is reached.
    pub fn record_matured_effects(
        &mut self,
        coinbase_height: u64,
        effects: NativeBlockEffects,
    ) -> Result<(), TenureAccountingError> {
        if self
            .matured_effects
            .insert(coinbase_height, effects)
            .is_some()
        {
            return Err(TenureAccountingError::DuplicateCoinbaseHeight);
        }
        Ok(())
    }

    /// The burnchain coinbase schedule, without which nothing is derived.
    #[must_use]
    pub const fn schedule(&self) -> Option<CoinbaseSchedule> {
        self.schedule
    }

    /// Adopt the earnings of a tenure that completed before this checkpoint.
    ///
    /// A checkpoint starts mid-tenure, so the fees of the tenure it lands in
    /// are only knowable from the node that produced the checkpoint.
    pub fn seed_earnings(&mut self, coinbase_height: u64, earnings: TenureEarnings) {
        self.earnings.insert(coinbase_height, earnings);
        self.forget_earnings_nothing_can_read();
    }

    /// Record a tenure whose start block was executed here.
    /// Forget every tenure from `coinbase_height` on, which a Bitcoin
    /// reorganization takes off the canonical chain along with its sortitions.
    pub fn retract_from(&mut self, coinbase_height: u64) {
        self.earnings.retain(|height, _| *height < coinbase_height);
        self.matured_effects
            .retain(|height, _| *height < coinbase_height);
        if self
            .started
            .is_some_and(|started| started >= coinbase_height)
        {
            // Not `None`: execution resumes inside the highest tenure that
            // survived, and this accounting *did* see that tenure's start block
            // — it is only later ones that were taken off the chain. Clearing
            // the marker instead silences `add_fees` for the rest of that
            // tenure permanently, because a start block is executed once.
            self.started = self.earnings.keys().next_back().copied();
        }
    }

    /// The span of coinbase heights whose earnings this can actually pay out.
    ///
    /// A checkpoint has to carry a full maturity window of these, because every
    /// tenure a node executes before its own mature pays out one from inside
    /// it. A short window executes perfectly until the first payout it cannot
    /// derive, which is why startup checks the span rather than waiting.
    ///
    /// *Contiguous*, ending at the highest known tenure, and not merely the
    /// lowest and highest keys. A hole is not a shorter window, it is a delayed
    /// one: the live mainnet state holds 167 tenures from 251,220 to 251,394 with
    /// 251,322 through 251,329 missing, so the outer pair says the window is 175
    /// long and the first payout it cannot make is still 27 tenures out — hours of
    /// execution, all of it thrown away, exactly the outcome saying so at startup
    /// exists to avoid. Counting from the top rather than the bottom because the
    /// tenures a node needs next are the ones nearest its tip.
    #[must_use]
    pub fn known_earnings_span(&self) -> Option<(u64, u64)> {
        let last = *self.earnings.keys().next_back()?;
        let mut first = last;
        for height in self.earnings.keys().rev().skip(1) {
            if *height != first.saturating_sub(1) {
                break;
            }
            first = *height;
        }
        Some((first, last))
    }

    /// The rewards a tenure earned, once they have been recorded.
    #[must_use]
    pub fn earnings_at(&self, coinbase_height: u64) -> Option<&TenureEarnings> {
        self.earnings.get(&coinbase_height)
    }

    /// The STX a tenure earned, as `get-tenure-info? block-reward` reports it.
    #[must_use]
    pub fn reward_for_tenure(&self, coinbase_height: u64) -> u128 {
        self.earnings.get(&coinbase_height).map_or(0, |earnings| {
            earnings.coinbase.saturating_add(earnings.fees)
        })
    }

    pub fn record_earnings(&mut self, coinbase_height: u64, earnings: TenureEarnings) {
        self.earnings.insert(coinbase_height, earnings);
        self.started = Some(coinbase_height);
        self.forget_earnings_nothing_can_read();
    }

    /// Drop tenures no payout, no check and no header can still ask for.
    ///
    /// This map is serialized into the chain ledger with **every** block, so
    /// letting it grow with the chain is not only a leak — it is a per-block cost
    /// that rises forever. About 130 bytes a tenure, and mainnet adds one every
    /// ten minutes.
    ///
    /// [`EARNINGS_KEPT`] is what the deepest reader needs plus a full maturity
    /// window of margin. `effects_for_tenure` reaches `matured - 1`, which is 101
    /// below the tip, so 102 would be correct and 201 leaves
    /// `known_earnings_span` a window it can still judge — the whole point of
    /// that span is to refuse a state that cannot pay, and a span pruned to the
    /// bone would report "exactly enough" for a state that is one tenure from
    /// failing.
    ///
    /// Pruning the *bottom* is safe because every reader counts down from the
    /// top: a payout from `coinbase_height`, the contiguous span, `add_fees` and
    /// `reward_for_tenure` on the tenure being executed. A tenure's
    /// `block_reward` outlives this map in the header store, which records it
    /// when the block is sealed.
    fn forget_earnings_nothing_can_read(&mut self) {
        while self.earnings.len() as u64 > EARNINGS_KEPT {
            let Some(oldest) = self.earnings.keys().next().copied() else {
                break;
            };
            self.earnings.remove(&oldest);
        }
    }

    /// Add the fees a block paid to the tenure that mined it, which only counts
    /// for a tenure this accounting saw from its first block.
    pub fn add_fees(&mut self, coinbase_height: u64, fees: u128) {
        if self.started != Some(coinbase_height) {
            return;
        }
        if let Some(earnings) = self.earnings.get_mut(&coinbase_height) {
            earnings.fees = earnings.fees.saturating_add(fees);
        }
    }

    /// Return the effects that mature at this tenure start.
    ///
    /// Failing loudly matters: a silently empty payout produces a state root
    /// that differs from the network's only once the block is already sealed.
    pub fn effects_for_tenure(
        &self,
        network: Network,
        coinbase_height: u64,
    ) -> Result<NativeBlockEffects, TenureAccountingError> {
        if let Some(effects) = self.matured_effects.get(&coinbase_height) {
            return Ok(effects.clone());
        }
        if coinbase_height <= MINER_REWARD_MATURITY {
            return Ok(NativeBlockEffects::default());
        }
        let matured = coinbase_height - MINER_REWARD_MATURITY;
        let earned = self
            .earnings
            .get(&matured)
            .ok_or(TenureAccountingError::UnknownTenure(matured))?;
        // Two tenures pay out here, one tenure apart: the maturing one's
        // coinbase, and the fees of the one before it.
        let previous = self.earnings.get(&matured.saturating_sub(1));
        let boot = || {
            PrincipalData::parse(network.boot_address())
                .expect("the boot address is a valid principal")
        };
        Ok(NativeBlockEffects {
            credits: vec![
                // The maturing tenure's recipient is paid its coinbase, and only
                // its coinbase: `calculate_miner_reward` gives the Nakamoto miner
                // share `(0, parent_fees, 0)`, so its anchored and confirmed fee
                // components are both zero.
                NativeStxCredit {
                    recipient: earned.recipient.clone(),
                    amount: earned.coinbase,
                },
                // The fees of the tenure *before* the maturing one, paid to that
                // tenure's own recipient. stacks-core reads both out of the
                // maturing tenure's schedule, whose `parent_fees` field holds the
                // fee total of its parent tenure, and resolves the recipient
                // through `get_parent_matured_miner` — but the pair is one
                // tenure's earnings, not two, and taking them from one entry is
                // what keeps them in step.
                //
                // Reading this off `make_scheduled_miner_reward` alone is not
                // possible, and reading it wrongly hides for a long time: with a
                // checkpoint whose `fees` field carried `parent_fees` verbatim,
                // paying `earned.fees` to `previous.recipient` is arithmetically
                // the same thing, so it matched every tenure the checkpoint
                // covered. It first differs at the first tenure nano totalled
                // itself, which is 100 tenures further on. Mainnet settled it at
                // 8,673,846: `SP70B98…` gains 15,114 uSTX, which is tenure
                // 251,320's own fee total, not tenure 251,321's 22,539,119.
                NativeStxCredit {
                    recipient: previous.map_or_else(boot, |previous| previous.recipient.clone()),
                    amount: previous.map_or(0, |previous| previous.fees),
                },
            ],
            liquid_supply_increase: earned.coinbase,
        })
    }
}

/// Errors raised while loading checkpointed tenure accounting.
