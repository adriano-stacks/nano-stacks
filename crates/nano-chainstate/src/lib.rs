#[derive(Debug)]
pub enum ChainStateError {
    Storage(MarfStoreError),
    Evaluation(ClarityEvalError),
    Execution(VmExecutionError),
    InvalidTransaction(String),
    TransactionFailure {
        result: Box<TransactionResult>,
        status: TransactionStatus,
    },
    UnsupportedPayload,
    /// Nothing stacked for a reward cycle, so it has no signer set.
    ///
    /// Distinct from an invalid transaction: the chain is well-formed and the
    /// block is honest, there is simply nobody to sign the cycle. It stays
    /// fatal — a cycle no one signs cannot be extended into — but a node that
    /// reports it as a consensus fault sends whoever reads the log looking in
    /// the wrong place, which on Hacknet it did.
    NoSignerSet(u64),
    StateRootMismatch {
        expected: TrieHash,
        actual: TrieHash,
    },
    FixtureExtensionParentTip {
        expected: [u8; 32],
        actual: Option<[u8; 32]>,
    },
    FixtureExtensionParentHeader([u8; 32]),
    /// The state kept beside the MARF could not be written or read back.
    Ledger(String),
}

impl std::fmt::Display for ChainStateError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::Storage(error) => write!(formatter, "state storage error: {error}"),
            Self::Evaluation(error) => write!(formatter, "Clarity evaluation error: {error}"),
            Self::Execution(error) => write!(formatter, "Clarity execution error: {error}"),
            Self::InvalidTransaction(error) => write!(formatter, "invalid transaction: {error}"),
            Self::TransactionFailure { status, .. } => {
                write!(formatter, "transaction failed: {status:?}")
            }
            Self::UnsupportedPayload => formatter.write_str("unsupported transaction payload"),
            Self::NoSignerSet(cycle) => write!(
                formatter,
                "reward cycle {cycle} has no signer set: nothing stacked for it"
            ),
            Self::StateRootMismatch { expected, actual } => write!(
                formatter,
                "state root mismatch: expected {expected}, got {actual}"
            ),
            Self::FixtureExtensionParentTip { expected, actual } => write!(
                formatter,
                "unauthenticated fixture extension parent {} is not the sealed tip {}",
                hex::encode(expected),
                actual.map_or_else(|| "<none>".to_owned(), hex::encode)
            ),
            Self::FixtureExtensionParentHeader(parent) => write!(
                formatter,
                "unauthenticated fixture extension parent {} has no complete recorded header",
                hex::encode(parent)
            ),
            Self::Ledger(error) => {
                write!(formatter, "the ledger kept beside the MARF: {error}")
            }
        }
    }
}

impl std::error::Error for ChainStateError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Storage(error) => Some(error),
            Self::Evaluation(_)
            | Self::Execution(_)
            | Self::InvalidTransaction(_)
            | Self::TransactionFailure { .. }
            | Self::UnsupportedPayload
            | Self::NoSignerSet(_)
            | Self::FixtureExtensionParentTip { .. }
            | Self::FixtureExtensionParentHeader(_)
            | Self::Ledger(_)
            | Self::StateRootMismatch { .. } => None,
        }
    }
}

